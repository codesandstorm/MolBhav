/**
 * Write the seeded prompt cards and the coverage grid:
 *   ml/gold/cards/cards.jsonl and ml/gold/cards/COVERAGE.md
 * Deterministic: same seed, same cards (packages/gold/test/cards.test.ts).
 * Usage: npm run gold:cards
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { coverageMarkdown, generateCards, PER_CLASS, SEED } from '../src/cards.ts';
import { CARDS_FILE, COVERAGE_FILE } from '../src/paths.ts';

const cards = generateCards(SEED);
mkdirSync(dirname(CARDS_FILE), { recursive: true });
writeFileSync(CARDS_FILE, cards.map((c) => JSON.stringify(c)).join('\n') + '\n');
writeFileSync(
  COVERAGE_FILE,
  `# Prompt-card coverage (seed ${SEED})

Generated by \`npm run gold:cards\` (packages/gold/scripts/cards.ts); do not edit by hand. ${cards.length} cards, ${PER_CLASS} per intended move. Cards are writing prompts, not messages.

What the grid guarantees: a stratified 20% test split holds **10 items per learned class** when the blind labels follow the intended moves. Labels that drift from the intent can leave a class below 10; the split script reports per-class test counts, and the eval report flags any class under 10 as "too few to score" [EVIDENCE: docs/product/04_research_integrity.md §2.2].

What it does not guarantee: **objection types get 19–38 cards each, about 4–8 test items, so every objection type is expected to be "too few to score" at 300 messages** [CALCULATION: the move × objection table below, × 0.2]. That is a decision for the owner (more messages, or report objections on train+dev cross-validation only).

${coverageMarkdown(cards)}
`,
);
console.log(`${cards.length} cards → ${CARDS_FILE}`);
